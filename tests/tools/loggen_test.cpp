using lv::loggen::Generator;
using lv::loggen::Profile;

std::string generate(Profile profile, std::uint64_t seed, std::uint64_t bytes)
{
    Generator generator(profile, seed);
    std::string out(generator.fileHeader());
    while (out.size() < bytes) {
        generator.appendLine(out);
    }
    return out;
}

// FNV-1a 64-bit; enough to detect any change of the generated bytes.
std::uint64_t fnv1a(std::string_view data)
{
    std::uint64_t hash = 0xCBF29CE484222325ULL;
    for (const char c : data) {
        hash ^= static_cast<unsigned char>(c);
        hash *= 0x100000001B3ULL;
    }
    return hash;
}

std::string readFile(const std::filesystem::path& path)
{
    std::ifstream in(path, std::ios::binary);
    return {std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
}

// Per-test temporary directory, removed afterwards.
class TempDir
{
public:
    TempDir()
        : m_path(std::filesystem::temp_directory_path() /
                 ("lv-loggen-" + std::to_string(std::random_device{}())))
    {
        std::filesystem::create_directories(m_path);
    }

    TempDir(const TempDir&) = delete;
    TempDir& operator=(const TempDir&) = delete;
    TempDir(TempDir&&) = delete;
    TempDir& operator=(TempDir&&) = delete;

    ~TempDir()
    {
        std::error_code ec;
        std::filesystem::remove_all(m_path, ec);
    }

    [[nodiscard]] const std::filesystem::path& path() const noexcept { return m_path; }

private:
    std::filesystem::path m_path;
};

struct LevelCounts
{
    std::uint64_t lines = 0;
    std::uint64_t error = 0;
    std::uint64_t warn = 0;
    std::uint64_t debug = 0;
    std::uint64_t info = 0;
    std::uint64_t bytes = 0;
};

LevelCounts countLevels(std::string_view text)
{
    LevelCounts counts;
    std::size_t start = 0;
    while (start < text.size()) {
        const std::size_t end = text.find('\n', start);
        REQUIRE(end != std::string_view::npos);
        const std::string_view line = text.substr(start, end - start);
        const std::string_view level = line.substr(24, 5);
        ++counts.lines;
        counts.bytes += line.size() + 1;
        if (level == "ERROR") {
            ++counts.error;
        } else if (level == "WARN ") {
            ++counts.warn;
        } else if (level == "DEBUG") {
            ++counts.debug;
        } else if (level == "INFO ") {
            ++counts.info;
        }
        start = end + 1;
    }
    return counts;
}

double percent(std::uint64_t part, std::uint64_t whole)
{
    return 100.0 * static_cast<double>(part) / static_cast<double>(whole);
}

